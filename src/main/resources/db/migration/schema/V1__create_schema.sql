CREATE TABLE manufacturer (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	name VARCHAR(255) NOT NULL,

	CONSTRAINT uq_manufacturer_name
		UNIQUE (name)
);

CREATE TABLE car_model (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	name VARCHAR(255) NOT NULL,
	manufacturer_id BIGINT NOT NULL,

	CONSTRAINT fk_car_model_manufacturer
		FOREIGN KEY (manufacturer_id)
		REFERENCES manufacturer (id),

	CONSTRAINT uq_car_model_manufacturer_name
		UNIQUE (manufacturer_id, name)
);

CREATE TABLE car (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	year SMALLINT NOT NULL,
	model_id BIGINT NOT NULL,

	CONSTRAINT fk_car_model
		FOREIGN KEY (model_id)
		REFERENCES car_model (id),

	CONSTRAINT uq_car_model_year
		UNIQUE (model_id, year)
);

CREATE TABLE category (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	name VARCHAR(255) NOT NULL,

	CONSTRAINT uq_category_name
		UNIQUE (name)
);

CREATE TABLE car_category (
	car_id BIGINT NOT NULL,
	category_id BIGINT NOT NULL,

	CONSTRAINT fk_car_category_car
		FOREIGN KEY (car_id)
		REFERENCES car (id)
		ON DELETE CASCADE,

	CONSTRAINT fk_car_category_category
		FOREIGN KEY (category_id)
		REFERENCES category (id)
		ON DELETE CASCADE,

	CONSTRAINT uq_car_category
		UNIQUE (car_id, category_id)
);

CREATE INDEX idx_car_category_category_id
	ON car_category (category_id);